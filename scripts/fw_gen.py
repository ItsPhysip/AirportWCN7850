#!/usr/bin/env python3
"""fw_gen.py <out.cpp> <file>... : embed firmware files for loadfirmware().

Each file becomes a const byte array, and qwz_fw_table lists them by basename
(the name qwz passes to loadfirmware(9), e.g. "qwz-wcn7850-hw2.0-amss").
"""
import os
import sys

out, files = sys.argv[1], sys.argv[2:]
with open(out, "w") as f:
    f.write("/* Generated by scripts/fw_gen.py from linux-firmware. Do not edit. */\n")
    f.write('#include "qwz_fw.h"\n\n')
    names = []
    for i, path in enumerate(files):
        data = open(path, "rb").read()
        sym = f"qwz_fw_{i}"
        names.append((os.path.basename(path), sym, len(data)))
        f.write(f"static const unsigned char {sym}[{len(data)}] = {{\n")
        for off in range(0, len(data), 32):
            f.write(",".join(str(b) for b in data[off:off + 32]) + ",\n")
        f.write("};\n\n")
    f.write("const struct qwz_fw_entry qwz_fw_table[] = {\n")
    for name, sym, size in names:
        f.write(f'\t{{ "{name}", {sym}, {size} }},\n')
    f.write("};\n")
    f.write(f"const int qwz_fw_count = {len(names)};\n")
print(f"{out}: {len(files)} images, {sum(n[2] for n in names)} bytes")
